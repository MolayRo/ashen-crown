def tome(emblem_rows):
    """正面立着的书：左书脊 c、封面 x/X/C、右侧书页 V/w，中央 3×3 徽记"""
    base = '''
................
................
...cccccccccc...
..cXXXXXXXXxcV..
..cXxxxxxxxCcw..
..cXxx@@@xxCcV..
..cXxx###xxCcw..
..cXxx$$$xxCcV..
..cXxxxxxxxCcw..
..cXxxxxxxxCcV..
..cXxxxxxxxCcw..
..cCCCCCCCCCcV..
...cccccccccVw..
................
................
................
'''
    a, b, c = emblem_rows
    return base.replace('@@@', a).replace('###', b).replace('$$$', c)


