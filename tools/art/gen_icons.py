DEFAULT = {'metal': 'iron', 'gold': 'gold', 'wood': 'wood', 'leather': 'leather', 'acc': 'fire',
           'acc2': 'cloth_crimson', 'gem': 'eye_blue', 'white': 'cloth_white'}


def art(s):
    lines = [ln.strip() for ln in s.strip('\n').split('\n')]
    return [ln for ln in lines if ln]


def render(a, mats, size):
    rows = art(a)
    grid = [[None] * size for _ in range(size)]
    for y, row in enumerate(rows[:size]):
        for x, ch in enumerate(row[:size]):
            if ch in '. ':
                continue
            role, idx = LEGEND[ch]
            if role == 'ink':
                grid[y][x] = INK
                continue
            if role == 'ink2':
                grid[y][x] = INK2
                continue
            r = PAL[mats.get(role, DEFAULT[role])]
            grid[y][x] = r[max(0, min(len(r) - 1, idx))]
    ring = []
    for y in range(size):
        for x in range(size):
            if grid[y][x] is not None:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                xx, yy = x + dx, y + dy
                if 0 <= xx < size and 0 <= yy < size:
                    c = grid[yy][xx]
                    if c is not None and c != INK and c != INK2:
                        ring.append((x, y))
                        break
    for x, y in ring:
        grid[y][x] = INK
    img = Image.new('RGBA', (size, size), CLEAR)
    px = img.load()
    for y in range(size):
        for x in range(size):
            if grid[y][x] is not None:
                px[x, y] = grid[y][x]
    return img


def recolor(a, mp):
    return a.translate(str.maketrans(mp))


