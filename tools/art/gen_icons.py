COLS = 8


def export():
    n16 = len(ICONS)
    rows16 = (n16 + COLS - 1) // COLS
    W = COLS * 16
    H = rows16 * 16 + 8
    sheet = Image.new('RGBA', (W, H), CLEAR)
    frames = {}
    for i, (name, a, mats) in enumerate(ICONS):
        x, y = (i % COLS) * 16, (i // COLS) * 16
        sheet.alpha_composite(render(a, mats, 16), (x, y))
        frames[name] = [x, y, 16, 16, 0, 0]
    y8 = rows16 * 16
    for i, (name, a, mats) in enumerate(WT):
        x = i * 8
        sheet.alpha_composite(render(a, mats, 8), (x, y8))
        frames[name] = [x, y8, 8, 8, 0, 0]
    sheet.save(os.path.join(ASSETS, 'icons.png'))
    with open(os.path.join(ASSETS, 'icons.json'), 'w', encoding='utf-8') as f:
        json.dump({'frames': frames, 'anims': {}}, f, ensure_ascii=False, separators=(',', ':'))
    return sheet, frames


def preview(sheet, frames, scale=6):
    os.makedirs(PREV, exist_ok=True)
    # 每个图标放在深色窗口底上，加上名字不方便（无字体），按表格排
    cell = 18
    names = [n for n, _, _ in ICONS] + [n for n, _, _ in WT]
    cols = 8
    rows = (len(names) + cols - 1) // cols
    img = Image.new('RGBA', (cols * cell + 2, rows * cell + 2), (36, 58, 122, 255))
    for i, n in enumerate(names):
        x0, y0, w, h, _, _ = frames[n]
        tile = sheet.crop((x0, y0, x0 + w, y0 + h))
        img.alpha_composite(tile, (2 + (i % cols) * cell + (16 - w) // 2, 2 + (i // cols) * cell + (16 - h) // 2))
    img.resize((img.width * scale, img.height * scale), Image.NEAREST).save(os.path.join(PREV, 'icons_all.png'))


if __name__ == '__main__':
    sheet, frames = export()
    print('icons.png', sheet.size, 'frames', len(frames))
    if '--preview' in sys.argv:
        preview(sheet, frames)
        print('preview ->', PREV)
